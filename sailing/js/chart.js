// The Sydney Harbour chart from harbour-data.js: projection, land shapes and the "is this land?" lookup.
export const MAP = window.HARBOUR; // generated by tools/build_harbour.py
export const W = MAP.W, H = MAP.H;

// Land from OpenStreetMap: one path for drawing, plus a 1/4-scale bitmap for fast "is this land?" lookups
export const landPath = new Path2D();
for (const r of MAP.land) {
  landPath.moveTo(r[0], r[1]);
  for (let i = 2; i < r.length; i += 2) landPath.lineTo(r[i], r[i + 1]);
  landPath.closePath();
}
const MASK = 4, mw = Math.ceil(W / MASK), mh = Math.ceil(H / MASK);
const landMask = (() => {
  const oc = document.createElement('canvas'); oc.width = mw; oc.height = mh;
  const o = oc.getContext('2d'); o.scale(1 / MASK, 1 / MASK); o.fill(landPath, 'evenodd');
  const px = o.getImageData(0, 0, mw, mh).data, m = new Uint8Array(mw * mh);
  for (let i = 0; i < m.length; i++) m[i] = px[i * 4 + 3] > 127;
  return m;
})();
export const isLand = (x, y) => {
  const i = Math.floor(x / MASK), j = Math.floor(y / MASK);
  return i >= 0 && j >= 0 && i < mw && j < mh && landMask[j * mw + i] === 1;
};
export const lonAt = x => MAP.lon0 + x * MAP.lonPerUnit, latAt = y => MAP.latTop - y * MAP.latPerUnit;
export const toXY = p => ({ x: (p.lon - MAP.lon0) / MAP.lonPerUnit, y: (MAP.latTop - p.lat) / MAP.latPerUnit });
// how far (up to len) you can go from p along unit vector d before reaching land
export const reach = (p, d, len) => { let r = 0; while (r < len && !isLand(p.x + d.x * (r + 5), p.y + d.y * (r + 5))) r += 5; return r; };

// Seeded random numbers, so the chart soundings and wind streaks are the same every load
let seed = 7;
export const rnd = () => (seed = (seed * 16807) % 2147483647) / 2147483647;

// Chart soundings (depth figures in metres), kept clear of the shore
export const soundings = Array.from({ length: 900 }, () => ({ x: rnd() * W, y: rnd() * H, d: Math.round(6 + rnd() * 24) }))
  .filter(s => [[0, 0], [40, 0], [-40, 0], [0, 40], [0, -40]].every(([dx, dy]) => !isLand(s.x + dx, s.y + dy)));
